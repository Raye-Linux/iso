"""Throughput: a fixed compile timed by hyperfine, and stress-ng's cpu and
matrix stressors on every CPU.

The compile is generated here, the same files every time, so no network
and no source tree are needed. Needs hyperfine, stress-ng, make and gcc.
"""

import json
import os
import pathlib
import re
import shlex
import sys
import tempfile

sys.dont_write_bytecode = True  # keep the tool folder clean
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import common  # noqa: E402

NAME = "throughput"
PER_BOOT = False


def write_compile_tree(path, files=64, functions=60):
    """A small C project that keeps every CPU busy for a few seconds."""
    os.makedirs(path, exist_ok=True)
    for i in range(files):
        lines = [f"/* generated by raye-bench: unit {i} */", "#include <string.h>", ""]
        for j in range(functions):
            lines += [
                f"static double f{j}(double x, int n) {{",
                "    double a[32]; memset(a, 0, sizeof a);",
                f"    for (int k = 0; k < n; k++) a[(k * {j + 3}) & 31] += x * k / (k + {j + 1}.0);",
                f"    return a[{j % 32}] + a[(n + {j}) & 31];",
                "}",
            ]
        body = " + ".join(f"f{j}(x, n)" for j in range(functions))
        lines += [f"double unit{i}(double x, int n) {{ return {body}; }}", ""]
        with open(os.path.join(path, f"u{i}.c"), "w") as f:
            f.write("\n".join(lines))
    objs = " ".join(f"u{i}.o" for i in range(files))
    with open(os.path.join(path, "Makefile"), "w") as f:
        f.write(f"OBJS = {objs}\nall: $(OBJS)\n%.o: %.c\n\t$(CC) -O2 -c $< -o $@\n"
                "clean:\n\trm -f *.o\n")


def parse_hyperfine(data):
    r = ((data or {}).get("results") or [{}])[0]
    return {k: (round(r[k], 4) if isinstance(r.get(k), (int, float)) else None)
            for k in ("median", "mean", "min", "max")}


def parse_stressng_yaml(text):
    """Bogo operations per second (real time), per stressor."""
    out, current = {}, None
    for line in (text or "").splitlines():
        m = re.match(r"\s*-\s*stressor:\s*(\S+)", line)
        if m:
            current = m.group(1).strip("'\"")
            continue
        m = re.match(r"\s*bogo-ops-per-second-real-time:\s*([\d.]+)", line)
        if m and current:
            out[current] = round(float(m.group(1)), 2)
    return out


def compile_seconds(workdir, runs, files):
    tree = os.path.join(workdir, "compile")
    write_compile_tree(tree, files=files)
    path = os.path.join(workdir, "hyperfine.json")
    res = common.run(["hyperfine", "--runs", str(runs), "--warmup", "1", "--style", "none",
                      "--prepare", f"make -s -C {shlex.quote(tree)} clean",
                      "--export-json", path, f"make -s -C {shlex.quote(tree)} -j{common.cpus()}"],
                     timeout=3600)
    if res is None or res.returncode != 0:
        return None
    with open(path) as f:
        return parse_hyperfine(json.load(f))["median"]


def stressng(stressor, seconds, workdir):
    path = os.path.join(workdir, f"{stressor}.yaml")
    res = common.run(["stress-ng", f"--{stressor}", "0", "--timeout", f"{seconds}s",
                      "--metrics-brief", "--yaml", path], timeout=seconds + 60)
    if res is None or res.returncode != 0 or not os.path.exists(path):
        return None
    with open(path) as f:
        return parse_stressng_yaml(f.read()).get(stressor)


def measure(opts=None):
    quick = getattr(opts, "quick", False)
    missing = [t for t in ("hyperfine", "stress-ng", "make", "gcc") if not common.have(t)]
    if missing:
        raise RuntimeError("missing: %s (sudo apt install hyperfine stress-ng build-essential)"
                           % ", ".join(missing))
    seconds = 5 if quick else 20
    with tempfile.TemporaryDirectory(prefix="raye-bench-") as d:
        return {
            "compile_s": compile_seconds(d, 2 if quick else 5, 16 if quick else 64),
            "cpu_ops_s": stressng("cpu", seconds, d),
            "matrix_ops_s": stressng("matrix", seconds, d),
        }


if __name__ == "__main__":
    print(json.dumps(measure(), indent=2))
